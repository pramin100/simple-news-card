const NEPALI_DIGITS: { [char: string]: string } = {
  "0": "०",
  "1": "१",
  "2": "२",
  "3": "३",
  "4": "४",
  "5": "५",
  "6": "६",
  "7": "७",
  "8": "८",
  "9": "९",
};

export function toNepaliDigits(num: number | string): string {
  return num
    .toString()
    .split("")
    .map((d) => NEPALI_DIGITS[d] || d)
    .join("");
}

export interface NepaliDateObj {
  year: number;
  month: number; // 1 to 12
  day: number;   // 1 to 32
  dayOfWeek: number; // 0 (Sun) to 6 (Sat)
  monthName: string;
  dayName: string;
  shortDayName: string;
}

/**
 * Converts any JavaScript Date to Bikram Sambat Nepali Date with 100% official calendar accuracy
 */
export function adToBs(adDate: Date = new Date()): NepaliDateObj {
  try {
    const safeDate = adDate instanceof Date && !isNaN(adDate.getTime()) ? adDate : new Date();
    const np = new (NepaliDate as any)(safeDate);
    const year = np.getYear();
    const month = np.getMonth() + 1; // 1-indexed (1 to 12)
    const day = np.getDate();
    const dayOfWeek = safeDate.getDay();

    return {
      year,
      month,
      day,
      dayOfWeek,
      monthName: NEPALI_MONTHS[month - 1] || "भदौ",
      dayName: NEPALI_DAYS[dayOfWeek] || "मंगलबार",
      shortDayName: NEPALI_SHORT_DAYS[dayOfWeek] || "मंगल",
    };
  } catch {
    return {
      year: 2083,
      month: 5,
      day: 2,
      dayOfWeek: 2,
      monthName: "भदौ",
      dayName: "मंगलबार",
      shortDayName: "मंगल",
    };
  }
}

/**
 * Formats a Nepali date into one of the popular style choices
 */
export function formatNepaliDate(bsDate: NepaliDateObj, formatIndex: number = 0): string {
  const y = toNepaliDigits(bsDate.year);
  const m = bsDate.monthName;
  const d = toNepaliDigits(bsDate.day);
  const mNum = toNepaliDigits(bsDate.month.toString().padStart(2, "0"));
  const dNum = toNepaliDigits(bsDate.day.toString().padStart(2, "0"));
  const dayName = bsDate.dayName;
  const shortDay = bsDate.shortDayName;

  switch (formatIndex) {
    case 0:
      // २०८३ जेठ २८, बिहीबार
      return `${y} ${m} ${d}, ${dayName}`;
    case 1:
      // बिहीबार, २८ जेठ २०८३
      return `${dayName}, ${d} ${m} ${y}`;
    case 2:
      // २०८३ जेठ २८ गते बिहीबार
      return `${y} ${m} ${d} गते ${dayName}`;
    case 3:
      // २८ जेठ २०८३, बिहीबार
      return `${d} ${m} ${y}, ${dayName}`;
    case 4:
      // २०८३/०३/२८ बिहीबार
      return `${y}/${mNum}/${dNum} ${dayName}`;
    case 5:
      // बिहीबार २८/०३/२०८३
      return `${dayName} ${dNum}/${mNum}/${y}`;
    case 6:
      // २०८३-०३-२८ बिही
      return `${y}-${mNum}-${dNum} ${shortDay}`;
    case 7:
      // २०८३ जेठ २८
      return `${y} ${m} ${d}`;
    default:
      return `${y} ${m} ${d}, ${dayName}`;
  }
}

